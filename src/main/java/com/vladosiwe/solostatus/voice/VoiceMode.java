package com.vladosiwe.solostatus.voice;

/** Режим голосовых команд. */
public enum VoiceMode {
    /** Голос выключен, микрофон не используется. */
    OFF,
    /** Распознавание только пока зажата клавиша голоса. */
    PUSH_TO_TALK,
    /** Постоянное прослушивание командных фраз (локально, звук никуда не отправляется). */
    ALWAYS
}
